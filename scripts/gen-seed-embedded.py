#!/usr/bin/env python3
"""Generates core/Sources/OMPRecipes/SeedEmbedded.generated.swift from Resources/seed/*.json (W02).

The generated file carries the seed as base64 so a build without a resource bundle (WebAssembly)
can load it with SeedLoader.load(SeedFiles). Usage: gen-seed-embedded.py [--check]
--check exits 1 if the committed file differs from what the JSON would generate."""
import base64, os, pathlib, sys

# OMP_RECIPES_DIR overrides the OMPRecipes source directory (used by the self-test on a temp copy).
root = pathlib.Path(os.environ.get("OMP_RECIPES_DIR") or
                    pathlib.Path(__file__).resolve().parent.parent / "core" / "Sources" / "OMPRecipes")
out = root / "SeedEmbedded.generated.swift"

def block(name: str) -> str:
    data = (root / "Resources" / "seed" / f"{name}.json").read_bytes()
    b64 = base64.b64encode(data).decode()
    lines = [b64[i:i + 100] for i in range(0, len(b64), 100)]
    return f'    static let {name} = """\n' + "\n".join("    " + l for l in lines) + '\n    """'

src = (
    "// GENERATED by scripts/gen-seed-embedded.py from Resources/seed/*.json. Do not edit.\n"
    "// A test fails if this file differs from the bundled JSON (W02).\n"
    "enum SeedEmbeddedBase64 {\n"
    + "\n".join(block(n) for n in ("catalog", "ingredients", "recipes"))
    + "\n}\n"
)
if "--check" in sys.argv:
    sys.exit(0 if out.exists() and out.read_text() == src else 1)
out.write_text(src)
